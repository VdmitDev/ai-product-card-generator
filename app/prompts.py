"""Промпты для генерации карточки.

Почему промпт устроен именно так (подробнее в README, раздел «Промпты»):

1. Инструкции и данные разделены. Системный промпт задаёт роль, источник фактов
   и запреты, а данные товара приходят отдельным сообщением внутри <product_data>.
   Модель не путает инструкции с данными, и фраза вроде «забудь правила» в
   описании товара ничего не сломает.

2. Запрет на выдумки стоит первым и перечисляет конкретные категории (IP, ГОСТ,
   пересчёт единиц), плюс короткий пример. Общее «не выдумывай» работает хуже,
   чем список того, что модели обычно дописывают сами.

3. У модели есть «легальное место» для знаний о типе прибора: поле missing_specs.
   Модель знает, что у датчика давления должна быть погрешность. Если эту мысль
   некуда деть, она впишет правдоподобное значение. С отдельным полем она пишет
   «нужно уточнить погрешность» вместо выдуманных «±0,5%».

4. Характеристики из текста описания идут с дословной цитатой. Цитату код ищет
   в описании (checks.py), и неподтверждённое значение в карточку не попадёт.
   Значения из specs модель вообще не переписывает: их переносит код.

5. Порядок полей в схеме: сначала разбор данных (что есть, чего нет, что
   противоречит), затем поисковые запросы, потом тексты. Модель пишет JSON по
   порядку, поэтому к описанию она подходит, уже разобрав данные, а SEO-тексты
   строит вокруг выбранных запросов.

6. Явно сказано, что важнее при конфликте: достоверность или объём. Иначе при
   скудных данных требование «800 символов» толкает модель к выдумкам.

7. Длины даны и в символах, и в словах: модели считают токены, а не буквы.
   Остальное добирает цикл исправлений в llm_service.py с точными цифрами.

8. Формат ответа задаётся через Structured Outputs (JSON Schema в strict-режиме),
   поэтому в промпте нет образца JSON: схему API соблюдает гарантированно,
   а промпт объясняет смысл полей.
"""

